/// <reference types="@cloudflare/vitest-pool-workers/types" />

/**
 * Resource-object cleanup against the real WorkspaceDO and R2 bindings.
 *
 * The Node suite proves the selection query's branches cheaply. These cases
 * prove constructor migration 21, routed WorkspaceDO SQL, trigger ordering,
 * and R2 deletion on the runtime that runs the maintenance alarm.
 */

import { env } from "cloudflare:workers";
import { reset, runInDurableObject } from "cloudflare:test";
import { beforeEach, describe, expect, it } from "vitest";

import { asWorkspaceId } from "@rally/contracts";

import { workspaceDOName } from "../src/durable-objects/names";
import type { WorkspaceDO } from "../src/durable-objects/workspace-do";
import {
  reapDeletedResourceObjects,
  releaseStagedResourceObject,
} from "../src/services/resource-object-cleanup";
import { withWorkspaceRuntimeDatabase } from "../src/services/workspace-runtime-database";

const WORKSPACE_ID = asWorkspaceId("00000000-0000-7000-8000-0000000009b0");
const RESOURCE_ID = "00000000-0000-7000-8000-0000000009b1";

function workspace(): DurableObjectStub<WorkspaceDO> {
  return env.WORKSPACE_DOS.get(env.WORKSPACE_DOS.idFromName(
    workspaceDOName("global", WORKSPACE_ID),
  ));
}

async function seedStagedObject(objectRef: string): Promise<void> {
  await env.PAYLOADS.put(objectRef, new TextEncoder().encode("generated bytes"));
  await runInDurableObject(workspace(), (_instance, state) => {
    state.storage.sql.exec(
      `INSERT INTO resource_object_deletion_outbox
       (object_ref, workspace_id, resource_id, object_kind, cleanup_eligible,
          created_at, updated_at)
       VALUES (?, ?, ?, 'original', 0, '2099-08-28T12:00:00.000Z',
               '2099-08-28T12:00:00.000Z')`,
      objectRef,
      WORKSPACE_ID,
      RESOURCE_ID,
    );
  });
}

function insertResourcePointer(state: DurableObjectState, objectRef: string): void {
  state.storage.sql.exec(
    `INSERT INTO resources
       (id, workspace_id, resource_type, provider, title, mime_type, content_ref,
        metadata_json, attachment_status, created_at, updated_at)
     VALUES (?, ?, 'generated_file', 'avalon_generated', 'Generated document',
             'text/plain', ?, '{}', 'attached', '2026-08-28T12:00:00.000Z',
             '2026-08-28T12:00:00.000Z')`,
    RESOURCE_ID,
    WORKSPACE_ID,
    objectRef,
  );
}

async function storedBytes(objectRef: string): Promise<string | null> {
  const object = await env.PAYLOADS.get(objectRef);
  if (!object) return null;
  return new TextDecoder().decode(await object.arrayBuffer());
}

beforeEach(async () => {
  await reset();
  await workspace().initializeWorkspace(WORKSPACE_ID, "wnam");
});

describe("resource-object cleanup on real workerd", () => {
  it("refreshes the maintenance alarm when a resource write activates staged bytes", async () => {
    const objectRef = "global/runtime-resource-alarm";
    await seedStagedObject(objectRef);
    const workspaceEnv = withWorkspaceRuntimeDatabase(env, WORKSPACE_ID);

    await workspaceEnv.DB.prepare(
      `INSERT INTO resources
         (id, workspace_id, resource_type, provider, title, mime_type, content_ref,
          metadata_json, attachment_status, created_at, updated_at)
       VALUES (?, ?, 'generated_file', 'avalon_generated', 'Generated document',
               'text/plain', ?, '{}', 'attached', '2026-08-28T12:00:00.000Z',
               '2026-08-28T12:00:00.000Z')`,
    ).bind(RESOURCE_ID, WORKSPACE_ID, objectRef).run();

    await runInDurableObject(workspace(), (_instance, state) => {
      expect(state.storage.sql.exec<{ count: number }>(
        `SELECT COUNT(*) AS count FROM _internal_durable_alarms
          WHERE kind = 'maintenance' AND alarm_key = 'resource_objects'`,
      ).one()).toEqual({ count: 1 });
    });
  });

  it("keeps staged R2 bytes through the pointer-publication gap", async () => {
    const objectRef = "global/runtime-resource-race";
    await seedStagedObject(objectRef);

    expect(await reapDeletedResourceObjects(env, WORKSPACE_ID)).toBe(0);
    await expect(storedBytes(objectRef)).resolves.toBe("generated bytes");
    await runInDurableObject(workspace(), (_instance, state) => {
      expect(state.storage.sql.exec<{ cleanup_eligible: number }>(
        "SELECT cleanup_eligible FROM resource_object_deletion_outbox WHERE object_ref = ?",
        objectRef,
      ).one()).toEqual({ cleanup_eligible: 0 });
      insertResourcePointer(state, objectRef);
    });

    // If a publisher could not clear its staging row, maintenance observes the
    // committed pointer and retires only the row, never the referenced bytes.
    expect(await reapDeletedResourceObjects(env, WORKSPACE_ID)).toBe(1);
    await expect(storedBytes(objectRef)).resolves.toBe("generated bytes");
    await runInDurableObject(workspace(), (_instance, state) => {
      expect(state.storage.sql.exec<{ count: number }>(
        "SELECT COUNT(*) AS count FROM resource_object_deletion_outbox",
      ).one()).toEqual({ count: 0 });
    });
  });

  it("releases a known failed publication to R2 cleanup", async () => {
    const objectRef = "global/runtime-resource-release";
    await seedStagedObject(objectRef);

    const workspaceEnv = withWorkspaceRuntimeDatabase(env, WORKSPACE_ID);
    await releaseStagedResourceObject(workspaceEnv.DB, WORKSPACE_ID, objectRef);
    await runInDurableObject(workspace(), (_instance, state) => {
      expect(state.storage.sql.exec<{ cleanup_eligible: number }>(
        "SELECT cleanup_eligible FROM resource_object_deletion_outbox WHERE object_ref = ?",
        objectRef,
      ).one()).toEqual({ cleanup_eligible: 1 });
    });

    const retired = await reapDeletedResourceObjects(env, WORKSPACE_ID);
    const cleanupState = await runInDurableObject(workspace(), (_instance, state) => (
      state.storage.sql.exec<{
        attempt_count: number;
        cleanup_eligible: number;
        last_error_code: string | null;
      }>(
        `SELECT attempt_count, cleanup_eligible, last_error_code
           FROM resource_object_deletion_outbox WHERE object_ref = ?`,
        objectRef,
      ).toArray()[0] ?? null
    ));
    expect({ retired, cleanupState }).toEqual({ retired: 1, cleanupState: null });
    await expect(storedBytes(objectRef)).resolves.toBeNull();
  });

  it("promotes a staged pointer when its resource is deleted first", async () => {
    const objectRef = "global/runtime-resource-deleted";
    await seedStagedObject(objectRef);
    await runInDurableObject(workspace(), (_instance, state) => {
      insertResourcePointer(state, objectRef);
      state.storage.sql.exec("DELETE FROM resources WHERE id = ?", RESOURCE_ID);
      expect(state.storage.sql.exec<{ cleanup_eligible: number }>(
        "SELECT cleanup_eligible FROM resource_object_deletion_outbox WHERE object_ref = ?",
        objectRef,
      ).one()).toEqual({ cleanup_eligible: 1 });
    });

    expect(await reapDeletedResourceObjects(env, WORKSPACE_ID)).toBe(1);
    await expect(storedBytes(objectRef)).resolves.toBeNull();
  });
});
