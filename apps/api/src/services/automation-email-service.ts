import { workstreamCanonicalUrl } from "@rally/contracts";

import type { Env } from "../env";
import { automationResultEmailHtml } from "./automation-email-content";
import { markdownToEmailText } from "./email-markdown";
import { sendResendEmail, singleLine } from "./resend";
import { workspaceRegionalDatabase } from "./workspace-runtime-database";

const MAX_RESULT_LENGTH = 40_000;

/**
 * The rendered ceiling, under Gmail's ~102 KB clip.
 *
 * The source cap above bounds Markdown; rendering inflates it — a dense
 * briefing, every bullet carrying bold, a link and a code span, measures over
 * seven times its source. Past Gmail's limit the tail of the briefing, the
 * button, and the "generated by AI" line all disappear behind "[Message
 * clipped]", so the cut is taken here, on what the reader will actually be
 * sent, rather than on the text it was rendered from.
 */
const MAX_RENDERED_BYTES = 90_000;

/** Subjects that must say what happened before the email is opened. */
const OUTCOME_PREFIX: Record<AutomationResultEmail["outcomeStatus"], string> = {
  completed: "",
  needs_input: "Action needed · ",
  failed: "Did not finish · ",
  stopped: "Stopped · ",
};

const EMAIL_ERRORS = {
  unavailable: { code: "automation_email_unavailable", message: "Automation result email is temporarily unavailable" },
  failed: { code: "automation_email_failed", message: "The automation result email could not be sent" },
};

export interface AutomationResultEmail {
  workspaceId: string;
  automationSubscriptionId: string;
  workstreamId: string;
  title: string;
  text: string;
  outcomeStatus: "completed" | "needs_input" | "failed" | "stopped";
}

export type AutomationEmailDelivery = "sent" | "skipped";

/**
 * Deliver from an AutomationRunContextV1 destination. The child owns the
 * result bytes; the parent receives only the receipt after this call settles.
 */
export async function deliverFrozenAutomationResultEmail(
  env: Env,
  input: AutomationResultEmail & {
    automationRunId: string;
    recipientEmail: string;
    recipientUserId: string;
  },
  request: typeof fetch = fetch,
): Promise<AutomationEmailDelivery> {
  const recipient = await workspaceRegionalDatabase(env).prepare(
    `SELECT user.timezone, user.email
       FROM users user
       JOIN workspace_members member ON member.user_id = user.id
      WHERE member.workspace_id = ? AND member.user_id = ? AND member.status = 'active'`,
  ).bind(input.workspaceId, input.recipientUserId).first<RecipientRow>();
  if (!recipient) return "skipped";
  // The address is re-checked, not only the membership. `resolveDeliveryTargets`
  // freezes the author's own address at acceptance, and an automation outlives
  // the address it was accepted with: someone who changes their email — or
  // whose old corporate mailbox is later reassigned to a different person —
  // would otherwise keep receiving this workspace's results at an address that
  // is no longer theirs. Refusing rather than re-targeting: the run was
  // authorized to mail a named address, and quietly sending its contents
  // somewhere else is not a smaller surprise than not sending it.
  if ((recipient.email ?? "").toLowerCase() !== input.recipientEmail.toLowerCase()) return "skipped";
  const name = singleLine(input.title) || "Rally automation";
  const ran = runDate(recipient.timezone);
  const subject = `${OUTCOME_PREFIX[input.outcomeStatus] ?? ""}${name} · ${ran}`;
  const body = resultBody(input.text);
  const workstreamUrl = workstreamCanonicalUrl(env.PUBLIC_WEB_BASE_URL, input.workstreamId);
  const delivery = await sendResendEmail(env, {
    recipientEmail: input.recipientEmail,
    subject,
    html: renderedWithinBudget({ name, heading: name, ran, outcomeStatus: input.outcomeStatus, body, workstreamUrl }),
    text: [subject, "", markdownToEmailText(body), "", `Open in Rally: ${workstreamUrl}`].join("\n"),
    idempotencyKey: `rally-automation-result/${input.automationSubscriptionId}/${input.automationRunId}/email`,
    category: "automation_result",
    region: env.AVALON_REGION,
    sender: "notification",
    errors: EMAIL_ERRORS,
  }, request);
  return delivery === "skipped" ? "skipped" : "sent";
}

interface RecipientRow {
  timezone: string | null;
  email: string | null;
}

function resultBody(text: string): string {
  const normalized = text.trim().replace(/\r\n/gu, "\n");
  if (normalized.length <= MAX_RESULT_LENGTH) return normalized;
  return truncateMarkdown(normalized, MAX_RESULT_LENGTH);
}

/**
 * A cut at a blank line rather than mid-sentence.
 *
 * Cutting on a character count lands inside a `**` pair or a `[label](url)`
 * often enough to matter, and the renderer then shows the surviving half of the
 * mark as punctuation — the exact symptom this module exists to remove. Falling
 * back to a hard cut keeps the bound absolute for text that has no blank line
 * in it at all.
 */
function truncateMarkdown(text: string, limit: number): string {
  const head = text.slice(0, limit - 1);
  const paragraph = head.lastIndexOf("\n\n");
  const cut = paragraph > limit / 2 ? head.slice(0, paragraph) : head;
  return `${cut.trimEnd()}…`;
}

/**
 * The rendered email, shortened until a client will show all of it.
 *
 * Re-rendering rather than cutting the HTML: a byte cut lands inside a tag and
 * a mail client is left holding half an element, while a shorter body is still
 * a whole document.
 */
function renderedWithinBudget(
  input: { name: string; heading: string; ran: string; outcomeStatus: AutomationResultEmail["outcomeStatus"]; body: string; workstreamUrl: string },
): string {
  let body = input.body;
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const html = automationResultEmailHtml({ ...input, body });
    if (new TextEncoder().encode(html).length <= MAX_RENDERED_BYTES || body.length < 2_000) return html;
    body = truncateMarkdown(body, Math.floor(body.length / 2));
  }
  return automationResultEmailHtml({ ...input, body });
}

/** The run's date, in the reader's own timezone, for the subject line. */
function runDate(timezone: string | null): string {
  try {
    return new Intl.DateTimeFormat("en-GB", {
      timeZone: timezone?.trim() || "UTC",
      day: "numeric",
      month: "short",
      year: "numeric",
    }).format(new Date());
  } catch {
    // A stored timezone is whatever the client sent when the account was made,
    // so an unknown zone must not stop the delivery.
    return new Intl.DateTimeFormat("en-GB", { timeZone: "UTC", day: "numeric", month: "short", year: "numeric" }).format(new Date());
  }
}

/**
 * The automation result email.
 *
 * The body is the run's final message, which is Markdown — the same text the
 * work stream shows. A mail client renders none of it, so it goes through the
 * shared `email-markdown` renderer rather than being escaped and line-broken:
 * before that, a briefing arrived as `## Heading` and `**bold**` in the
 * reader's inbox. The shell around it is the digest email's, because the two
 * are the same product arriving the same way.
 */
