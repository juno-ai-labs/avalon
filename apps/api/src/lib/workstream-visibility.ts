/**
 * The one answer to "may this person read this work stream".
 *
 * It lives here because it was previously written out three times — the sidebar
 * list, the single-row read, and HyperSight's authorizer — and the third copy
 * silently missed `scope`, which let any member reach another person's private
 * work stream by id. A rule duplicated per call site is a rule that will be
 * incomplete somewhere.
 *
 * Two conditions, both of which must hold:
 *
 * - **`visibility`** — a `private` work stream is readable only by an active
 *   participant. A work stream started from a private connector conversation is
 *   private from birth and its participants are that conversation's members, so
 *   this clause is what carries the source conversation's audience into Avalon.
 * - **automation ownership** — a work stream generated by a *personal*
 *   automation is readable by that automation's owner even though the row
 *   carries no participants, which is why this is still its own clause rather
 *   than folded into `visibility`.
 *
 * `system_kind` is deliberately absent: whether a work stream is machinery
 * decides whether it is *listed*, not who may read it, and callers that list
 * apply that separately.
 */

/**
 * The rule as SQL, for a query with the `workstreams` table aliased as `w`.
 *
 * Self-contained on purpose — it correlates to `automation_subscriptions`
 * itself rather than requiring a join the caller has to remember to add, so
 * pasting it into a new query cannot quietly weaken it.
 *
 * `visibility` is compared with `IS NOT` rather than `<>` because the column is
 * nullable until `0078` tightens it: `<>` is `NULL` for a row an old Worker
 * inserted between the migration and the deploy, and a `NULL` condition excludes
 * the row from *every* branch, which reads as "nobody may see their own work
 * stream" rather than as the intended default. `0077`'s insert trigger fills the
 * column in the same statement, so this is a guard against the window rather
 * than a state anything durably observes.
 *
 * `reader` is the SQL expression naming the person doing the reading, and is
 * the only reason this is a function: the work-stream room binds by position
 * (`?3`) and its eviction sweep asks the question of a whole column at once
 * (`wm.user_id`), and neither could use a fragment that hard-coded a single
 * anonymous `?`. It is interpolated, so it takes a constant written at the call
 * site and never a value from a request.
 */
export function workstreamVisibilitySql(reader: string): string {
  return `(
    w.visibility IS NOT 'private' OR EXISTS (
      SELECT 1 FROM workstream_participants scoped
       WHERE scoped.workstream_id = w.id AND scoped.user_id = ${reader} AND scoped.removed_at IS NULL
    )
  )
  AND (
    w.automation_subscription_id IS NULL
    OR EXISTS (
      SELECT 1 FROM automation_subscriptions owned
       WHERE owned.id = w.automation_subscription_id
         AND (owned.scope = 'workspace' OR owned.owner_user_id = ${reader})
    )
    OR EXISTS (
      SELECT 1 FROM workstream_participants involved
       WHERE involved.workstream_id = w.id AND involved.user_id = ${reader} AND involved.removed_at IS NULL
    )
  )`;
}

/**
 * The rule for a query that binds the reading user anonymously.
 *
 * Binds three values, all the reading user's id, in the order they appear. Use
 * {@link workstreamVisibilityBindings} rather than writing them out.
 */
export const WORKSTREAM_VISIBILITY_SQL = workstreamVisibilitySql("?");

/** The bindings {@link WORKSTREAM_VISIBILITY_SQL} consumes, in order. */
export function workstreamVisibilityBindings(userId: string): [string, string, string] {
  return [userId, userId, userId];
}
